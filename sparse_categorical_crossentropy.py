"""
MULTICLASS Training: 7 classes (HAM10000)
==============================================
Adapted translation from the binary script to direct multiclass classification (7 options).

What it does
------------
1. (Optional) Organizes HAM10000 into Datasets/training|validation/<class>/
   with an 80/20 split BY LESION (prevents data leakage).
2. Loads images in uint8 and keeps integer labels (0 to 6) for the 7 classes.
3. Builds an EfficientNet (B0/B4) with a 7-output softmax head and trains it in two phases:
   head (frozen backbone) -> fine-tuning (last N layers, low lr).
4. Evaluates on validation: accuracy, macro and weighted precision/recall/F1, multiclass confusion matrix.
5. Creates a run folder with EVERYTHING that occurred:
      training_summary.txt       <- complete summary (config, environment, data, epochs, etc.)
      console.log                <- copy of the console output
      epoch_history.csv          <- metrics per epoch
      validation_predictions.csv <- probabilities and predicted class per validation image
      metrics.json               <- final and phase metrics
      training_curves.png / confusion_matrix.png
      <name>_multiclass.keras    <- trained model (+ <name>_multiclass.json with metadata)

Pre-processing (same 4 options as entrenamiento_binario_mel.py)
---------------------------------------------------------------
  --preprocessing baseline | hair_removal | color_constancy | contrast_focused
  Applied on image load, identically to training and validation (never differs by split).
  Do NOT combine with a dataset already generated by balance_dataset_new.py --method X
  using the same X: the pre-processing would be applied twice.

Examples
--------
  python sparse_categorical_crossentropy.py --name Exp_Baseline --dataset-dir Datasets_safe --preprocessing baseline
  python sparse_categorical_crossentropy.py --name Exp_DullRazor --dataset-dir Datasets_safe --preprocessing hair_removal

For educational use only — not intended for clinical diagnosis.
"""

